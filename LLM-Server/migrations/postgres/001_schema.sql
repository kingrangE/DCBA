CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE COLLATION IF NOT EXISTS dcba_username (provider = icu, locale = 'und-u-ks-level1', deterministic = false);
CREATE TABLE "user" (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name char(10) COLLATE dcba_username NOT NULL UNIQUE,
    password varchar(60) NOT NULL,
    slack_id varchar(255),
    created_at timestamp(6)
);
CREATE TABLE exercise (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    subject varchar(30) NOT NULL,
    level varchar(8) NOT NULL,
    question text NOT NULL,
    answer text NOT NULL,
    created_at timestamp(6) DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE selected_exercise (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint REFERENCES "user"(id),
    exercise_id bigint REFERENCES exercise(id),
    custom_answer text,
    review_again boolean NOT NULL DEFAULT false,
    UNIQUE (user_id, exercise_id)
);
CREATE TABLE banned_exercise (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint REFERENCES "user"(id),
    exercise_id bigint REFERENCES exercise(id),
    UNIQUE (user_id, exercise_id)
);
CREATE TABLE generation_task (task_id varchar(128) PRIMARY KEY, exercise_id bigint NOT NULL);
CREATE TABLE deleted_exercise (exercise_id bigint PRIMARY KEY);
CREATE TABLE exercise_feedback_rubric (
    exercise_id bigint PRIMARY KEY REFERENCES exercise(id) ON DELETE CASCADE,
    criteria_json json NOT NULL
);
CREATE INDEX idx_exercise_subject_level ON exercise(subject, level, id);
CREATE INDEX idx_exercise_level ON exercise(level, id);
CREATE INDEX idx_selected_exercise ON selected_exercise(exercise_id);
CREATE INDEX idx_banned_exercise ON banned_exercise(exercise_id);
CREATE INDEX exercise_question_trgm ON exercise USING gin (lower(question) gin_trgm_ops);
CREATE TABLE dcba_cutover (source_engine varchar(8) PRIMARY KEY, imported_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP);
